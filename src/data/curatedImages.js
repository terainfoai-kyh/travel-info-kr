  const t = (spotTitle || '').toLowerCase();
  const c = (city || '').toLowerCase();
  const cat = (category || '').toLowerCase();

  // 1. Palaces & Historic Gates (Gyeongbokgung, Changdeok, Bulguksa) - Priority 1 to prevent night mis-match
