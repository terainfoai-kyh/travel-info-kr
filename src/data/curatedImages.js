/**
 * 🎨 Smart Photo Matcher: Returns high-resolution, vibrant, perfectly themed visual
 */
export function getCuratedSpotImage(spotTitle = '', city = '서울', category = '', index = 0) {
  const cleanTitle = (spotTitle || '').toLowerCase();
  const cleanCity = (city || '').toLowerCase();
  const cleanCat = (category || '').toLowerCase();

  // 1. Jeju Island Matching
  if (cleanCity.includes('제주') || cleanCity.includes('서귀포') || cleanCity.includes('jeju')) {
    if (cleanTitle.includes('카페') || cleanTitle.includes('도넛') || cleanTitle.includes('커피') || cleanCat.includes('cafe')) {
      const arr = CURATED_KOREA_PHOTOS.jeju.cafe;
      return arr[index % arr.length];
    }
    if (cleanTitle.includes('돼지') || cleanTitle.includes('고기') || cleanTitle.includes('식당') || cleanTitle.includes('맛집') || cleanTitle.includes('국수')) {
      const arr = CURATED_KOREA_PHOTOS.jeju.food;
      return arr[index % arr.length];
    }
    if (cleanTitle.includes('바다') || cleanTitle.includes('해변') || cleanTitle.includes('해수욕장') || cleanTitle.includes('협재') || cleanTitle.includes('함덕') || cleanTitle.includes('애월')) {
      const arr = CURATED_KOREA_PHOTOS.jeju.ocean;
      return arr[index % arr.length];
    }
    const arr = CURATED_KOREA_PHOTOS.jeju.nature;
    return arr[index % arr.length];
  }

  // 2. Busan Matching
  if (cleanCity.includes('부산') || cleanCity.includes('busan')) {
    if (cleanTitle.includes('야경') || cleanTitle.includes('광안') || cleanTitle.includes('드론') || cleanTitle.includes('더베이')) {
      const arr = CURATED_KOREA_PHOTOS.busan.night;
      return arr[index % arr.length];
    }
    if (cleanTitle.includes('카페') || cleanTitle.includes('커피') || cleanCat.includes('cafe')) {
      const arr = CURATED_KOREA_PHOTOS.busan.cafe;
      return arr[index % arr.length];
    }
    if (cleanTitle.includes('자갈치') || cleanTitle.includes('국밥') || cleanTitle.includes('식당') || cleanTitle.includes('맛집')) {
      const arr = CURATED_KOREA_PHOTOS.busan.food;
      return arr[index % arr.length];
    }
    const arr = CURATED_KOREA_PHOTOS.busan.ocean;
    return arr[index % arr.length];
  }

  // 3. Gyeongju Matching
  if (cleanCity.includes('경주') || cleanCity.includes('gyeongju')) {
    if (cleanTitle.includes('카페') || cleanTitle.includes('황리단') || cleanCat.includes('cafe')) {
      const arr = CURATED_KOREA_PHOTOS.gyeongju.cafe;
      return arr[index % arr.length];
    }
    const arr = CURATED_KOREA_PHOTOS.gyeongju.history;
    return arr[index % arr.length];
  }

  // 4. Gangwon / Gangneung / Sokcho Matching
  if (cleanCity.includes('강릉') || cleanCity.includes('속초') || cleanCity.includes('강원') || cleanCity.includes('gangneung')) {
    if (cleanTitle.includes('카페') || cleanTitle.includes('커피') || cleanCat.includes('cafe')) {
      const arr = CURATED_KOREA_PHOTOS.gangwon.cafe;
      return arr[index % arr.length];
    }
    const arr = CURATED_KOREA_PHOTOS.gangwon.nature;
    return arr[index % arr.length];
  }

  // 5. Jeonju Matching
  if (cleanCity.includes('전주') || cleanCity.includes('jeonju')) {
    const arr = CURATED_KOREA_PHOTOS.jeju.nature;
    return CURATED_KOREA_PHOTOS.jeonju.hanok[index % CURATED_KOREA_PHOTOS.jeonju.hanok.length];
  }

  // 6. Seoul / General Fallback Matching
  if (cleanTitle.includes('카페') || cleanTitle.includes('성수') || cleanTitle.includes('디올') || cleanTitle.includes('커피') || cleanTitle.includes('베이커리') || cleanCat.includes('cafe')) {
    const arr = CURATED_KOREA_PHOTOS.seoul.cafe;
    return arr[index % arr.length];
  }
  if (cleanTitle.includes('야경') || cleanTitle.includes('타워') || cleanTitle.includes('한강') || cleanTitle.includes('밤')) {
    const arr = CURATED_KOREA_PHOTOS.seoul.night;
    return arr[index % arr.length];
  }
  if (cleanTitle.includes('쇼핑') || cleanTitle.includes('홍대') || cleanTitle.includes('명동') || cleanTitle.includes('더현대')) {
    const arr = CURATED_KOREA_PHOTOS.seoul.shopping;
    return arr[index % arr.length];
  }
  if (cleanTitle.includes('식당') || cleanTitle.includes('맛집') || cleanTitle.includes('고기') || cleanTitle.includes('시장') || cleanCat.includes('food')) {
    const arr = CURATED_KOREA_PHOTOS.seoul.food;
    return arr[index % arr.length];
  }

  const arr = CURATED_KOREA_PHOTOS.seoul.palace;
  return arr[index % arr.length];
}
